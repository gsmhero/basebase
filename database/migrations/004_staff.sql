ALTER TABLE users
  ADD COLUMN owner_id INT UNSIGNED NULL,
  ADD COLUMN perms VARCHAR(120) NOT NULL DEFAULT '',
  ADD KEY users_owner (owner_id);

ALTER TABLE users ADD CONSTRAINT fk_users_owner FOREIGN KEY (owner_id) REFERENCES users(id) ON DELETE CASCADE;

CREATE TABLE invites (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  owner_id INT UNSIGNED NOT NULL,
  email VARCHAR(190) NOT NULL,
  name VARCHAR(120) NOT NULL DEFAULT '',
  perms VARCHAR(120) NOT NULL DEFAULT '',
  token CHAR(48) NOT NULL UNIQUE,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  used_at DATETIME NULL,
  KEY inv_owner (owner_id),
  FOREIGN KEY (owner_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

